import { afterAll, beforeEach, describe, expect, it } from "vitest";
import { getEntitledMedia, getProfile } from "@/server/services/club";
import { createPost, deletePost, myPosts, normalizePost, updatePost, type PostInput } from "@/server/services/studio";
import type { SeedResult } from "@/server/seed";
import { asViewer, closePool, resetDb, rlsError, system, viewer } from "./helpers";

let s: SeedResult;
beforeEach(async () => {
  s = await resetDb();
});
afterAll(closePool);

const base: PostInput = { access: "members", teaser: "Studio notes, week one.", body: "The full letter.", mediaKind: "image", publish: "now" };
const handleOf = async (id: string) => (await system((q) => q.one<{ handle: string }>(`select handle::text as handle from app.creators where user_id = $1`, [id])))!.handle;

describe("post validation", () => {
  it("enforces teaser, body, price, set size and schedule window", () => {
    const now = new Date("2026-11-05T12:00:00Z");
    expect(() => normalizePost({ ...base, teaser: " " }, now)).toThrow(/teaser/);
    expect(() => normalizePost({ ...base, teaser: "x".repeat(141) }, now)).toThrow();
    expect(() => normalizePost({ ...base, body: "x".repeat(5001) }, now)).toThrow();
    expect(() => normalizePost({ ...base, access: "ppv" }, now)).toThrow(/price/);
    expect(() => normalizePost({ ...base, access: "ppv", priceCents: 99 }, now)).toThrow(/price/);
    expect(() => normalizePost({ ...base, access: "ppv", priceCents: 12.5 }, now)).toThrow(/price/);
    expect(normalizePost({ ...base, access: "ppv", priceCents: 1200 }, now).priceCents).toBe(1200);
    // Price is ignored unless the post is sold individually.
    expect(normalizePost({ ...base, priceCents: 5 }, now).priceCents).toBeNull();
    expect(() => normalizePost({ ...base, mediaKind: "set", mediaCount: 1 }, now)).toThrow(/set/);
    expect(normalizePost({ ...base, mediaKind: "image", mediaCount: 40 }, now).mediaCount).toBe(1);
    expect(() => normalizePost({ ...base, publish: "schedule", scheduleAt: new Date("2026-11-05T12:00:30Z") }, now)).toThrow(/minute/);
    expect(() => normalizePost({ ...base, publish: "schedule", scheduleAt: new Date("2028-01-01T00:00:00Z") }, now)).toThrow(/year/);
    expect(() => normalizePost({ ...base, body: "barely legal" }, now)).toThrow(/can't be published/);
    expect(() => normalizePost({ ...base, access: "everyone" as never }, now)).toThrow();
  });
});

describe("creator posts (PostgreSQL)", () => {
  it("drafts and scheduled posts are invisible and locked to members until published", async () => {
    const isadora = await viewer(s.creatorIds.isadora);
    const member = await viewer(s.memberId); // VIP of Isadora
    const handle = await handleOf(isadora.id);
    const draft = await createPost(isadora, { ...base, teaser: "A draft.", publish: "draft" });
    const later = await createPost(isadora, { ...base, teaser: "Later.", publish: "schedule", scheduleAt: new Date(Date.now() + 3_600_000) });
    const live = await createPost(isadora, { ...base, teaser: "Live now." });

    const teasers = (await getProfile(member, handle))!.posts.map((p) => p.teaser);
    expect(teasers).toContain("Live now.");
    expect(teasers).not.toContain("A draft.");
    expect(teasers).not.toContain("Later.");
    // The creator's own public profile shows published posts only, too.
    expect((await getProfile(isadora, handle))!.posts.map((p) => p.teaser)).not.toContain("A draft.");
    // Direct RLS: no row, no content, no media.
    for (const id of [draft, later]) {
      expect(await asViewer(member, (q) => q.query(`select 1 from app.posts where id = $1`, [id]))).toHaveLength(0);
      expect(await asViewer(member, (q) => q.query(`select 1 from app.post_content where post_id = $1`, [id]))).toHaveLength(0);
      expect(await getEntitledMedia(member, id, 0)).toBeNull();
    }
    expect(await getEntitledMedia(member, live, 0)).not.toBeNull();

    const mine = await myPosts(isadora);
    expect(Object.fromEntries(mine.filter((p) => [draft, later, live].includes(p.id)).map((p) => [p.teaser, p.state]))).toEqual({ "A draft.": "draft", "Later.": "scheduled", "Live now.": "published" });
    // Publishing a draft makes it visible.
    await updatePost(isadora, draft, { ...base, teaser: "A draft." });
    expect((await getProfile(member, handle))!.posts.map((p) => p.teaser)).toContain("A draft.");
  });

  it("media is generated by the server, never supplied by the client", async () => {
    const isadora = await viewer(s.creatorIds.isadora);
    const id = await createPost(isadora, { ...base, mediaKind: "set", mediaCount: 6 });
    const row = await system((q) => q.one<{ media: { study: { hair: string } }[] }>(`select media from app.post_content where post_id = $1`, [id]));
    expect(row!.media).toHaveLength(1);
    expect(["long", "bun", "crop", "wrap"]).toContain(row!.media[0].study.hair);
  });

  it("app layer: members can't post; creators can't edit or delete another creator's post", async () => {
    const member = await viewer(s.memberId);
    const isadora = await viewer(s.creatorIds.isadora);
    const zara = await viewer(s.creatorIds.zara);
    await expect(createPost(member, base)).rejects.toMatchObject({ code: "forbidden" });
    const id = await createPost(isadora, base);
    await expect(updatePost(zara, id, { ...base, teaser: "Hijacked" })).rejects.toMatchObject({ code: "not_found" });
    await expect(deletePost(zara, id)).rejects.toMatchObject({ code: "not_found" });
    await expect(createPost(await viewer(s.creatorIds.rhea), base)).resolves.toBeTruthy(); // drafts allowed before verification
  });

  it("RLS: no inserting as someone else, no self-unhiding, no moving posts, no owner rewrites", async () => {
    const isadora = s.creatorIds.isadora;
    const zara = s.creatorIds.zara;
    expect(await rlsError(zara, `insert into app.posts (creator_id, access, teaser, published_at) values ($1, 'preview', 'x', now())`, [isadora], 1)).toBe("42501");
    expect(await rlsError(s.memberId, `insert into app.posts (creator_id, access, teaser, published_at) values ($1, 'preview', 'x', now())`, [s.memberId], 1)).toBe("42501");
    expect(await rlsError(isadora, `insert into app.posts (creator_id, access, teaser, published_at, hidden_at) values ($1, 'preview', 'x', now(), now())`, [isadora], 1)).toBe("42501");

    const id = await createPost(await viewer(isadora), base);
    await asViewer(await viewer(s.ownerId), (q) => q.query(`update app.posts set hidden_at = now(), hidden_reason = 'review' where id = $1`, [id]));
    expect(await rlsError(isadora, `update app.posts set hidden_at = null where id = $1`, [id], 1)).toBe("42501");
    expect(await rlsError(isadora, `update app.posts set creator_id = $2 where id = $1`, [id, zara], 1)).toBe("42501");
    expect(await rlsError(s.ownerId, `update app.posts set teaser = 'owner rewrite' where id = $1`, [id], 2)).toBe("42501");
    // Another creator's update/delete silently matches nothing.
    await asViewer({ id: zara, aal: 1 }, (q) => q.query(`update app.posts set teaser = 'z' where id = $1`, [id]));
    await asViewer({ id: zara, aal: 1 }, (q) => q.query(`delete from app.posts where id = $1`, [id]));
    await asViewer({ id: zara, aal: 1 }, (q) => q.query(`update app.post_content set body = 'z' where post_id = $1`, [id]));
    const after = await system((q) => q.one<{ teaser: string; body: string }>(`select p.teaser, pc.body from app.posts p join app.post_content pc on pc.post_id = p.id where p.id = $1`, [id]));
    expect(after).toEqual({ teaser: base.teaser, body: base.body });
    expect(await rlsError(zara, `insert into app.post_content (post_id, body) values ($1, 'z') on conflict (post_id) do update set body = 'z'`, [id], 1)).toBe("42501");
  });

  it("a bought post can't be deleted, unpublished or re-gated", async () => {
    const mireille = await viewer(s.creatorIds.mireille);
    const ppv = (await myPosts(mireille)).find((p) => p.purchased)!;
    expect(ppv).toMatchObject({ access: "ppv", state: "published" });
    await expect(deletePost(mireille, ppv.id)).rejects.toMatchObject({ code: "conflict" });
    await expect(updatePost(mireille, ppv.id, { ...base, access: "members", teaser: ppv.teaser })).rejects.toMatchObject({ code: "conflict" });
    await expect(updatePost(mireille, ppv.id, { ...base, access: "ppv", priceCents: 1200, teaser: ppv.teaser, publish: "draft" })).rejects.toMatchObject({ code: "conflict" });
    // Editing copy (keeping access and publish time) is allowed.
    await updatePost(mireille, ppv.id, { access: "ppv", priceCents: 1500, teaser: "Edited teaser.", mediaKind: "set", mediaCount: 36, publish: "now" });
    const after = (await myPosts(mireille)).find((p) => p.id === ppv.id)!;
    expect(after).toMatchObject({ teaser: "Edited teaser.", priceCents: 1500, publishedAt: ppv.publishedAt });
    expect(await rlsError(s.creatorIds.mireille, `delete from app.posts where id = $1 returning 1`, [ppv.id], 1)).toBeNull();
    expect(await system((q) => q.one(`select 1 from app.posts where id = $1`, [ppv.id]))).toBeTruthy();
  });

  it("delete removes the post and its content, and is audited", async () => {
    const isadora = await viewer(s.creatorIds.isadora);
    const id = await createPost(isadora, base);
    await deletePost(isadora, id);
    expect(await system((q) => q.query(`select 1 from app.post_content where post_id = $1`, [id]))).toHaveLength(0);
    const actions = await system((q) => q.query<{ action: string }>(`select action from app.audit_log where target_id = $1 order by id`, [id]));
    expect(actions.map((a) => a.action)).toEqual(["post.create", "post.delete"]);
  });
});
